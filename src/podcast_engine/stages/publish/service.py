from typing import Any
from uuid import UUID

from podcast_engine.common.context import (
    HOST_NAMES,
    PROMPT_VERSIONS,
    PipelineContext,
    get_context,
)
from podcast_engine.common.logging import get_logger
from podcast_engine.common.models import EpisodeStatus, ScriptLine
from podcast_engine.common.queue import Stage
from podcast_engine.common.repository import ShowRecord, StoredItem
from podcast_engine.common.storage import feed_key

AI_DISCLOSURE = "This episode was generated by AI from the cited sources."
# Show notes name the product, not the hosted model behind it. The episode's manifest still records
# the exact model (``script_backend``) and each voice's full credit, as the transparency NFR asks.
PRODUCT = "Oasis"


def _writer(backend: str | None) -> str:
    """Name what wrote the script, for the show notes.

    Show notes name the product, not the hosted model behind it; the manifest still records the
    exact model.

    Args:
        backend: The script backend from the manifest, or None.

    Returns:
        The product's name, marked when the offline writer wrote it.
    """
    return f"{PRODUCT} (offline writer)" if backend == "offline-extractive" else PRODUCT


def _branded(credit: str) -> str:
    """Credit a voice to the product instead of Gemini TTS.

    Args:
        credit: The voice's credit line.

    Returns:
        The credit with the product's name.
    """
    return credit.replace("Gemini TTS", PRODUCT)


log = get_logger("publish")


def with_disclosure(show_notes: str) -> str:
    """Make sure show notes carry the AI-generated label exactly once, at the top (FR13).

    Args:
        show_notes: The notes.

    Returns:
        The notes with the disclosure first.
    """
    if AI_DISCLOSURE in show_notes:
        return show_notes
    return f"{AI_DISCLOSURE}\n\n{show_notes}"


def notes_key(episode_id: UUID) -> str:
    """Return the object key of an episode's show notes.

    Args:
        episode_id: The episode.

    Returns:
        The notes' key in object storage.
    """
    return f"notes/{episode_id}.md"


def clock(seconds: float) -> str:
    """Format seconds as a chapter start time.

    Args:
        seconds: Seconds from the start.

    Returns:
        ``MM:SS``.
    """
    return f"{int(seconds // 60):02d}:{int(seconds % 60):02d}"


def build_show_notes(
    *,
    show: ShowRecord,
    episode_id: UUID,
    revision: int,
    script: dict[int, list[ScriptLine]],
    chapters: list[tuple[float, str]],
    item_of_chunk: dict[UUID, UUID],
    items: dict[UUID, StoredItem],
    manifest: dict[str, Any],
    note: str = "",
    music_credits: list[str] | None = None,
) -> str:
    """Write an episode's show notes (FR5).

    Chapters with each claim and its citation numbers, then the sources, numbered in order of first
    citation, the show's attribution, and how the episode was made: writer, voices in host order,
    music credits, prompts and seed.

    Args:
        show: The show.
        episode_id: The episode.
        revision: The episode's revision of the show.
        script: The script's lines, by segment.
        chapters: Each segment's (start in seconds, title).
        item_of_chunk: The source item each cited chunk belongs to.
        items: The show's source items, by id.
        manifest: How the episode was made.
        note: A line to show under the title, such as which segments a refresh updated.
        music_credits: Credit lines for the music used.

    Returns:
        The notes as Markdown.
    """
    numbers: dict[UUID, int] = {}
    for position in sorted(script):
        for line in script[position]:
            for claim in line.claims:
                for chunk_id in claim.chunk_ids:
                    if chunk_id in item_of_chunk:
                        numbers.setdefault(item_of_chunk[chunk_id], len(numbers) + 1)
    lines = [f"# {show.topic}", ""]
    if note:
        lines += [f"_{note}_", ""]
    for (start, title), position in zip(chapters, sorted(script), strict=False):
        lines += [f"## {clock(start)}  {title}", ""]
        for line in script[position]:
            for claim in line.claims:
                refs = ", ".join(
                    f"[{numbers[item_of_chunk[c]]}]" for c in claim.chunk_ids if c in item_of_chunk
                )
                lines.append(f"- {claim.text} {refs}".rstrip())
        lines.append("")
    lines += ["## Sources", ""]
    lines += [
        f"{n}. [{items[i].title}]({items[i].url})"
        for i, n in sorted(numbers.items(), key=lambda kv: kv[1])
    ]
    if show.attribution:
        lines += ["", show.attribution]
    voices = manifest.get("voices", {})
    order = {host: n for n, host in enumerate(HOST_NAMES)}
    lines += [
        "",
        "## How this episode was made",
        "",
        f"- Revision {revision}, episode `{episode_id}`",
        f"- Script and fact-check: {_writer(manifest.get('script_backend'))}; prompts "
        f"{PROMPT_VERSIONS}",
        "- Voices: "
        + "; ".join(
            f"{host}: {_branded(voices[host]['credit'])}"
            for host in sorted(voices, key=lambda h: order.get(h, len(order)))
        ),
        f"- Seed: {manifest.get('seed')}",
    ]
    if music_credits:
        lines.append("- Music: " + "; ".join(music_credits))
    return with_disclosure("\n".join(lines))


def build_feed(show: ShowRecord, entries: list[dict[str, Any]], base_url: str) -> bytes:
    """Build the show's RSS feed.

    Every title is labelled AI-generated and every description carries the disclosure (FR13).
    Entries are added oldest first, because feedgen lists the last added first.

    Args:
        show: The show.
        entries: Each published episode's id, revision, date, notes and audio size.
        base_url: The public base URL that feed links start with.

    Returns:
        The RSS 2.0 document with iTunes tags.
    """
    from feedgen.feed import FeedGenerator

    feed = FeedGenerator()
    feed.load_extension("podcast")
    feed.title(f"{show.topic} [AI-generated]")
    feed.link(href=f"{base_url}/api/v1/feeds/{show.show_id}/rss.xml", rel="self")
    feed.description(with_disclosure(f"An AI-generated show about {show.topic}."))
    feed.language(show.language)
    feed.podcast.itunes_category("Technology")
    for item in sorted(entries, key=lambda e: e["published_at"]):
        entry = feed.add_entry()
        entry.id(str(item["episode_id"]))
        entry.guid(str(item["episode_id"]), permalink=False)
        entry.title(f"{show.topic} (revision {item['revision']}) [AI-generated]")
        entry.description(item["notes"])
        entry.published(item["published_at"])
        entry.enclosure(
            f"{base_url}/api/v1/episodes/{item['episode_id']}/audio.wav",
            str(item["bytes"]),
            "audio/wav",
        )
    rss: bytes = feed.rss_str(pretty=True)
    return rss


def publish_episode(episode_id: UUID, ctx: PipelineContext | None = None) -> Stage | None:
    """Write the show notes with citations, then rebuild the show's feed (stage 8, FR10).

    The manifest records the exact script model, prompts, embedder, seed and ranking profile. A
    refresh's notes say which segments it updated. A remix keeps its original date in the feed.

    Args:
        episode_id: The episode to publish.
        ctx: Shared clients; built from settings when omitted.

    Returns:
        None: publishing ends the pipeline.

    Raises:
        ValueError: The episode has no assembled audio.
    """
    from podcast_engine.stages.script.service import script_lines

    ctx = ctx or get_context()
    episode = ctx.repo.get_episode(episode_id)
    show = ctx.repo.get_show(episode.show_id)
    if episode.audio_key is None or episode.assembly is None:
        raise ValueError("The episode has no assembled audio to publish.")
    script = script_lines(episode.script)
    chunk_ids = {
        c
        for lines in script.values()
        for line in lines
        for claim in line.claims
        for c in claim.chunk_ids
    }
    item_of_chunk = {cid: chunk.item_id for cid, chunk in ctx.repo.get_chunks(chunk_ids).items()}
    items = {item.item_id: item for item in ctx.repo.list_items(show.show_id)}
    settings = ctx.settings
    manifest = dict(episode.manifest or {})
    manifest.update(
        {
            "episode_id": str(episode_id),
            "revision": episode.revision,
            "script_backend": f"{settings.llm_provider}:{settings.llm_model}"
            if settings.llm_enabled
            else "offline-extractive",
            "prompt_versions": PROMPT_VERSIONS,
            "embedder": settings.embedding_model,
            "seed": settings.seed,
            "ranking_profile": show.ranking_profile,
        }
    )
    note = ""
    if episode.changed_item_ids is not None:
        changed = sorted(
            s.position
            for s in ctx.repo.list_segments(episode_id)
            if set(s.source_item_ids) & set(episode.changed_item_ids)
        )
        note = f"Updated: segment(s) {changed} refreshed from a changed source." if changed else ""
    notes = build_show_notes(
        show=show,
        episode_id=episode_id,
        revision=episode.revision,
        script=script,
        chapters=[(float(start), str(title)) for start, title in episode.assembly["chapters"]],
        item_of_chunk=item_of_chunk,
        items=items,
        manifest=manifest,
        note=note,
        music_credits=list((episode.assembly.get("music") or {}).get("credits", [])),
    )
    ctx.store.put(notes_key(episode_id), notes.encode("utf-8"), "text/markdown; charset=utf-8")
    ctx.repo.update_episode(
        episode_id,
        notes_key=notes_key(episode_id),
        manifest=manifest,
        status=EpisodeStatus.PUBLISHED,
        published_at=episode.published_at or ctx.now(),
        error=None,
    )
    entries = rebuild_feed(show.show_id, ctx)
    log.info(
        "episode_published",
        episode_id=str(episode_id),
        revision=episode.revision,
        feed_entries=entries,
    )
    return None


def rebuild_feed(show_id: UUID, ctx: PipelineContext | None = None) -> int:
    """Rewrite the show's feed from its published episodes.

    Called after each publish, and after a published episode is deleted. With nothing published the
    feed is removed, so podcast apps see the show as empty rather than a stale entry.

    Args:
        show_id: The show.
        ctx: Shared clients; built from settings when omitted.

    Returns:
        How many episodes the feed lists.
    """
    ctx = ctx or get_context()
    show = ctx.repo.get_show(show_id)
    published = ctx.repo.list_published(show_id)
    if not published:
        ctx.store.delete(feed_key(show_id))
        log.info("feed_removed", show_id=str(show_id))
        return 0
    entries = [
        {
            "episode_id": e.episode_id,
            "revision": e.revision,
            "published_at": e.published_at,
            "notes": ctx.store.get(e.notes_key).decode("utf-8") if e.notes_key else AI_DISCLOSURE,
            "bytes": (e.assembly or {}).get("audio_bytes", 0),
        }
        for e in published
    ]
    ctx.store.put(
        feed_key(show_id),
        build_feed(show, entries, ctx.settings.public_feed_base_url),
        "application/rss+xml",
    )
    return len(entries)
